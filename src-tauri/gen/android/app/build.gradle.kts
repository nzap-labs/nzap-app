/**
 * Release signing. CI and maintainers provide `keystore.properties` next to
 * this project (never committed) or the NZAP_KEYSTORE_* environment
 * variables; without either, release builds fall back to the debug key so
 * they stay installable for testing.
 */
val keystoreProperties = Properties().apply {
    val propFile = rootProject.file("keystore.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}
fun signingValue(key: String, env: String): String? =
    keystoreProperties.getProperty(key) ?: System.getenv(env)?.takeIf { it.isNotBlank() }

