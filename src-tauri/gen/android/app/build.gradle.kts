/**
 * One version code per APK: `base * 10 + abi` for the per-ABI flavors, so
 * stores always prefer the most specific APK and upgrades never go backwards.
 * The universal APK keeps `base * 10`.
 */
val abiVersionOffsets = mapOf("armeabi-v7a" to 1, "arm64-v8a" to 2, "x86" to 3, "x86_64" to 4)
val flavorAbis = mapOf("arm" to "armeabi-v7a", "arm64" to "arm64-v8a", "x86" to "x86", "x86_64" to "x86_64")
androidComponents {
    onVariants { variant ->
        val base = variant.outputs.first().versionCode.orNull ?: 1
        val abi = flavorAbis[variant.flavorName]
        val offset = abi?.let { abiVersionOffsets[it] } ?: 0
        variant.outputs.forEach { output -> output.versionCode.set(base * 10 + offset) }
    }
}

